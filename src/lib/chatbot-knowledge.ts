function scoreKnowledgeItem(item: KnowledgeItem, normalizedQuery: string): number {
  let score = 0;
  for (const kw of item.keywords) {
    const kwLower = kw.toLowerCase();
    if (normalizedQuery === kwLower) {
      score += 20;
    } else if (normalizedQuery.includes(kwLower)) {
      score += Math.max(4, kwLower.length);
    }
  }

  const titleLower = item.title.toLowerCase();
  const tokens = normalizedQuery.split(/\s+/).filter((t) => t.length >= 2);
  for (const token of tokens) {
    if (titleLower.includes(token)) {
      score += 3;
    }
  }
  return score;
}

/**
 * 3. ฟังก์ชันค้นหาคำตอบจาก Knowledge Base อย่างชาญฉลาด (Semantic Keyword Matcher)
 */
export function searchKnowledgeBase(query: string, userRole: string): KnowledgeItem | null {
  const lower = query.toLowerCase().replace(/[?.,!เเ]/g, '').trim();
  const role = (userRole || 'USER').toUpperCase();

  let bestMatch: KnowledgeItem | null = null;
  let maxScore = 0;

  for (const item of LAB_KNOWLEDGE_BASE) {
    if (item.allowedRoles && !item.allowedRoles.includes(role)) {
      continue;
    }
    const score = scoreKnowledgeItem(item, lower);
    if (score > maxScore) {
      maxScore = score;
      bestMatch = item;
    }
  }

  return maxScore >= 4 ? bestMatch : null;
}

/**
 * 4. ค้นหาคู่มือการใช้งานระบบสูงสุด 3 หัวข้อ (สำหรับ Gemini Tool `search_system_guide`)
 */
export function searchSystemGuides(topic: string, userRole: string = 'USER'): SystemGuideResult[] {
  const normalized = (topic || '').toLowerCase().replace(/[?.,!]/g, '').trim();
  const role = (userRole || 'USER').toUpperCase();

  const scored = LAB_KNOWLEDGE_BASE.filter(
    (item) => !item.allowedRoles || item.allowedRoles.includes(role)
  )
    .map((item) => ({
      item,
      score: scoreKnowledgeItem(item, normalized),
    }))
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3);

  const fallback =
    scored.length > 0
      ? scored.map((s) => s.item)
      : LAB_KNOWLEDGE_BASE.filter((i) => ['how_to_use', 'contact_location', 'roles_permissions'].includes(i.id));

  return fallback.map((item) => ({
    id: item.id,
    title: item.title,
    category: item.category,
    route: item.route,
    content: item.answer(role),
  }));
}
