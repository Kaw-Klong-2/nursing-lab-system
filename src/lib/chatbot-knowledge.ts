/**
 * 3. ฟังก์ชันค้นหาคำตอบจาก Knowledge Base อย่างชาญฉลาด (Semantic Keyword Matcher)
 */
export function searchKnowledgeBase(query: string, userRole: string): KnowledgeItem | null {
  const lower = query.toLowerCase().replace(/[?.,!เเ]/g, '').trim();

  // จัดอันดับความตรงกันของ Keywords
  let bestMatch: KnowledgeItem | null = null;
  let maxScore = 0;

  for (const item of LAB_KNOWLEDGE_BASE) {
    let score = 0;
    for (const kw of item.keywords) {
      const kwLower = kw.toLowerCase();
      if (lower === kwLower) {
        score += 15; // ตรงเป๊ะทั้งประโยค
      } else if (lower.includes(kwLower)) {
        score += Math.max(3, kwLower.length); // มีคำค้นอยู่ข้างใน
      }
    }
    if (score > maxScore) {
      maxScore = score;
      bestMatch = item;
    }
  }

  // กำหนดเกณฑ์ขั้นต่ำว่าต้องตรงกันพอสมควร
  return maxScore >= 3 ? bestMatch : null;
}
