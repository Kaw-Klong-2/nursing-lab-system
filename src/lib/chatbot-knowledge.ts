/**
 * 1. ฟังก์ชันตรวจจับและตอบคำถามเรื่อง วัน เวลา ปฏิทิน และสถานะเปิดแล็บแบบทันที (Deterministic Engine)
 */
export function answerDateTimeAndGeneralQuery(
  query: string,
  userRole: string = 'USER'
): { text: string; quickReplies?: Array<{ label: string; textToSend: string }> } | null {
  const lower = query.toLowerCase().replace(/[?.,!เเ]/g, '').trim();

  const isAskingTime =
    lower.includes('กี่โมง') ||
    lower.includes('เวลาเท่าไหร่') ||
    lower.includes('ตอนนี้กี่โมง') ||
    lower.includes('เวลาอะไร') ||
    lower.includes('เวลาปัจจุบัน') ||
    lower.includes('ขอดูเวลา') ||
    lower.includes('เวลาตอนนี้');
  const isAskingDate =
    lower.includes('วันที่เท่าไหร่') ||
    lower.includes('วันนี้วันอะไร') ||
    lower.includes('วันที่เท่าไร') ||
    lower.includes('พรุ่งนี้วันอะไร') ||
    lower.includes('เมื่อวานวันอะไร') ||
    lower.includes('เดือนนี้เดือนอะไร') ||
    lower.includes('ปีนี้ปีอะไร') ||
    lower.includes('พ.ศ.') ||
    lower.includes('ค.ศ.');
  const isAskingLabOpenNow =
    lower.includes('ตอนนี้แล็บเปิด') ||
    lower.includes('วันนี้แล็บเปิด') ||
    lower.includes('แล็บเปิดอยู่ไหม') ||
    lower.includes('แล็บปิดหรือยัง') ||
    lower.includes('เปิดทำการอยู่ไหม') ||
    lower.includes('แล็บเปิดไหม');

  const isAskingOpeningSchedule =
    lower.includes('เปิดกี่โมง') ||
    lower.includes('ปิดกี่โมง') ||
    lower.includes('เวลาทำการ') ||
    lower.includes('คืนของกี่โมง') ||
    lower.includes('ส่งของคืนกี่โมง') ||
    lower.includes('เปิดปิดกี่โมง');

  if (!isAskingTime && !isAskingDate && !isAskingLabOpenNow && !isAskingOpeningSchedule) {
    return null;
  }

  const now = new Date();
  const bangkokFormatter = new Intl.DateTimeFormat('th-TH', {
    timeZone: 'Asia/Bangkok',
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  });

  const parts = bangkokFormatter.formatToParts(now);
  const getPart = (type: string) => parts.find((p) => p.type === type)?.value || '';

  const weekday = getPart('weekday');
  const day = getPart('day');
  const month = getPart('month');
  const year = getPart('year');
  const hourStr = getPart('hour');
  const minuteStr = getPart('minute');
  const hour = parseInt(hourStr, 10);
  const minute = parseInt(minuteStr, 10);
  const timeCurrentMinutes = hour * 60 + minute;

  const isWeekend = weekday.includes('เสาร์') || weekday.includes('อาทิตย์');
  const isWithinHours = timeCurrentMinutes >= 8 * 60 + 30 && timeCurrentMinutes < 16 * 60 + 30;
  const isLabOpenNow = !isWeekend && isWithinHours;

  if (isAskingLabOpenNow) {
    if (isWeekend) {
      return {
        text: `🔴 **ขณะนี้ห้องปฏิบัติการพยาบาล ปิดทำการครับ**\n\n• วันนี้เป็น **${weekday}** (วันหยุดสุดสัปดาห์)\n• เวลาปัจจุบัน: **${hourStr}:${minuteStr} น.**\n• ห้องปฏิบัติการเปิดให้บริการอีกครั้งใน **วันจันทร์ เวลา 08:30 - 16:30 น.** ครับ\n*(ท่านยังสามารถส่งคำขอจองห้องแล็บหรือขอยืม-เบิกล่วงหน้าผ่านระบบได้ตลอด 24 ชม. ครับ)*`,
        quickReplies: [
          { label: '🏢 วิธีจองห้องแล็บ', textToSend: 'วิธีจองห้องแล็บทำยังไง' },
          { label: '📅 ตารางห้องวันนี้', textToSend: 'วันนี้มีห้องไหนว่างบ้าง' },
        ],
      };
    }

    if (isLabOpenNow) {
      return {
        text: `🟢 **ขณะนี้ห้องปฏิบัติการพยาบาล เปิดทำการอยู่ครับ!**\n\n• วันนี้: **${weekday}ที่ ${day} ${month} พ.ศ. ${year}**\n• เวลาปัจจุบัน: **${hourStr}:${minuteStr} น.**\n• เวลาทำการ: **08:30 - 16:30 น.**\n• จุดติดต่อ: อาคารวิทยบริการ ชั้น 3 คณะพยาบาลศาสตร์ ยินดีต้อนรับครับ 😊`,
        quickReplies: [
          { label: '📅 ตารางห้องวันนี้', textToSend: 'วันนี้มีห้องไหนว่างบ้าง' },
          { label: '📍 แล็บอยู่ที่ไหน', textToSend: 'แล็บอยู่ที่ไหน' },
        ],
      };
    }

    const statusReason =
      timeCurrentMinutes < 8 * 60 + 30
        ? 'ยังไม่ถึงเวลาเปิดทำการ (เปิด 08:30 น.)'
        : 'หมดเวลาให้บริการของวันนี้แล้ว (ปิด 16:30 น.)';
    return {
      text: `🔴 **ขณะนี้ห้องปฏิบัติการพยาบาล ปิดทำการครับ** (${statusReason})\n\n• เวลาปัจจุบัน: **${hourStr}:${minuteStr} น.**\n• เวลาทำการปกติ: **วันจันทร์ - ศุกร์ 08:30 - 16:30 น.**\n*(ท่านยังสามารถส่งคำขอจองห้องแล็บหรือยืม-เบิกพัสดุล่วงหน้าไว้ในระบบได้ตลอดเวลาครับ)*`,
      quickReplies: [
        { label: '🏢 วิธีจองห้องแล็บ', textToSend: 'วิธีจองห้องแล็บทำยังไง' },
        { label: '🛒 วิธียืม-เบิกพัสดุ', textToSend: 'วิธียืมและเบิกพัสดุทำยังไง' },
      ],
    };
  }

  if (isAskingOpeningSchedule && !isAskingTime) {
    return {
      text: `⏰ **เวลาทำการของห้องปฏิบัติการพยาบาล:**\n\n• **วันเปิดให้บริการ:** วันจันทร์ - ศุกร์\n• **เวลาให้บริการ:** **08:30 - 16:30 น.** (หยุดวันเสาร์-อาทิตย์ และวันหยุดนักขัตฤกษ์)\n• **กำหนดส่งคืนพัสดุ:** กรุณานำมาส่งคืนก่อนเวลา **16:30 น.** ของวันที่ครบกำหนดครับ\n• **จุดติดต่อ:** อาคารวิทยบริการ ชั้น 3 คณะพยาบาลศาสตร์\n\n*(ขณะนี้เวลา **${hourStr}:${minuteStr} น.** ${isLabOpenNow ? '🟢 ห้องแล็บกำลังเปิดทำการอยู่ครับ' : '🔴 ห้องแล็บปิดทำการอยู่ครับ'})*`,
      quickReplies: [
        { label: '📍 แล็บอยู่ที่ไหน', textToSend: 'แล็บอยู่ที่ไหน' },
        { label: '📅 ตารางห้องวันนี้', textToSend: 'วันนี้มีห้องไหนว่างบ้าง' },
      ],
    };
  }

  if (isAskingTime && !isAskingDate) {
    return {
      text: `⏰ ขณะนี้เวลา **${hourStr}:${minuteStr} น.** (ประเทศไทย, GMT+7)\nประจำ**${weekday}ที่ ${day} ${month} พ.ศ. ${year}** ครับ\n\nสถานะห้องแล็บขณะนี้: ${isLabOpenNow ? '🟢 **เปิดทำการอยู่** (08:30 - 16:30 น.)' : '🔴 **ปิดทำการ** (เปิด 08:30 - 16:30 น. จันทร์-ศุกร์)'}`,
      quickReplies: [
        { label: '📅 ตารางห้องวันนี้', textToSend: 'วันนี้มีห้องไหนว่างบ้าง' },
        { label: '💡 ทำอะไรได้บ้าง', textToSend: 'ทำอะไรได้บ้าง' },
      ],
    };
  }

  return {
    text: `📅 วันนี้คือ **${weekday}ที่ ${day} ${month} พ.ศ. ${year}**\n(ค.ศ. ${now.getFullYear()}) ขณะนี้เวลา **${hourStr}:${minuteStr} น.** ครับ 😊`,
    quickReplies: [
      { label: '💡 ทำอะไรได้บ้าง', textToSend: 'ทำอะไรได้บ้าง' },
      { label: '📅 ตารางห้องวันนี้', textToSend: 'วันนี้มีห้องไหนว่างบ้าง' },
    ],
  };
}

