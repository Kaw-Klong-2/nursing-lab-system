def build_presentation():
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank_layout = prs.slide_layouts[6]

    # Colors
    BG_DARK = RGBColor(15, 23, 42)       # Slate 900
    CARD_BG = RGBColor(30, 41, 59)       # Slate 800
    CARD_BORDER = RGBColor(51, 65, 85)   # Slate 700
    TEAL = RGBColor(20, 184, 166)        # Teal 500
    EMERALD = RGBColor(16, 185, 129)     # Emerald 500
    WHITE = RGBColor(248, 250, 252)
    MUTED = RGBColor(148, 163, 184)
    AMBER = RGBColor(251, 191, 36)

    for s in SLIDES_DATA:
        slide = prs.slides.add_slide(blank_layout)

        # Background fill
        bg = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, prs.slide_height
        )
        bg.fill.solid()
        bg.fill.fore_color.rgb = BG_DARK
        bg.line.fill.background()

        # Top Accent Bar
        top_bar = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, Inches(0.12)
        )
        top_bar.fill.solid()
        top_bar.fill.fore_color.rgb = TEAL
        top_bar.line.fill.background()

        # Header Badge (Slide num + Menu path + Role)
        header_box = slide.shapes.add_textbox(Inches(0.5), Inches(0.25), Inches(12.3), Inches(0.4))
        tf_h = header_box.text_frame
        tf_h.word_wrap = True
        p_h = tf_h.paragraphs[0]
        p_h.text = f"SLIDE {s['num']:02d}/20   |   {s['section']}   |   {s['menu']}   |   ผู้ใช้งาน: {s['roles']}"
        p_h.font.name = "Sarabun"
        p_h.font.size = Pt(12)
        p_h.font.bold = True
        p_h.font.color.rgb = TEAL

        # Title & Subtitle
        title_box = slide.shapes.add_textbox(Inches(0.5), Inches(0.65), Inches(12.3), Inches(1.1))
        tf_t = title_box.text_frame
        tf_t.word_wrap = True
        p_t = tf_t.paragraphs[0]
        p_t.text = s["title"]
        p_t.font.name = "Sarabun"
        p_t.font.size = Pt(24)
        p_t.font.bold = True
        p_t.font.color.rgb = WHITE

        p_sub = tf_t.add_paragraph()
        p_sub.text = s["subtitle"]
        p_sub.font.name = "Sarabun"
        p_sub.font.size = Pt(14)
        p_sub.font.color.rgb = MUTED

        # Left Column: 3 Step Cards
        y_top = Inches(1.85)
        card_h = Inches(1.42)
        gap = Inches(0.18)

        for idx, (st_title, st_desc) in enumerate(s["steps"]):
            cy = y_top + idx * (card_h + gap)
            card = slide.shapes.add_shape(
                MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.5), cy, Inches(7.1), card_h
            )
            card.fill.solid()
            card.fill.fore_color.rgb = CARD_BG
            card.line.color.rgb = CARD_BORDER
            card.line.width = Pt(1.2)

            tb = slide.shapes.add_textbox(Inches(0.68), cy + Inches(0.12), Inches(6.75), card_h - Inches(0.2))
            tf = tb.text_frame
            tf.word_wrap = True
            p1 = tf.paragraphs[0]
            p1.text = f"▶ {st_title}"
            p1.font.name = "Sarabun"
            p1.font.size = Pt(16)
            p1.font.bold = True
            p1.font.color.rgb = AMBER

            p2 = tf.add_paragraph()
            p2.text = st_desc
            p2.font.name = "Sarabun"
            p2.font.size = Pt(13.5)
            p2.font.color.rgb = WHITE

        # Right Column: Screenshot Frame
        img_card = slide.shapes.add_shape(
            MSO_SHAPE.ROUNDED_RECTANGLE, Inches(7.85), Inches(1.85), Inches(4.95), Inches(4.62)
        )
        img_card.fill.solid()
        img_card.fill.fore_color.rgb = CARD_BG
        img_card.line.color.rgb = TEAL
        img_card.line.width = Pt(1.5)

        img_path = os.path.join("d:\\LAB-system", s["image"].replace("/", os.sep))
        if os.path.exists(img_path):
            try:
                slide.shapes.add_picture(
                    img_path, Inches(8.0), Inches(2.0), width=Inches(4.65)
                )
            except Exception:
                pass

        # Outcome Footer Banner
        footer = slide.shapes.add_shape(
            MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.5), Inches(6.62), Inches(12.3), Inches(0.62)
        )
        footer.fill.solid()
        footer.fill.fore_color.rgb = RGBColor(19, 78, 74)  # Deep Teal
        footer.line.color.rgb = EMERALD
        footer.line.width = Pt(1)

        ft_box = slide.shapes.add_textbox(Inches(0.7), Inches(6.7), Inches(11.9), Inches(0.45))
        tf_f = ft_box.text_frame
        tf_f.word_wrap = True
        pf = tf_f.paragraphs[0]
        pf.text = f"ผลลัพธ์สำคัญ (Key Outcome):  {s['outcome']}"
